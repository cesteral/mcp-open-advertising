import { SERVER_TYPES, meets } from "../lib/contract-tiers.mjs";
import { REFRESH_DAYS } from "../check/check-platform-facts.mjs";
import { templateType } from "./render.mjs";

/** The scaffold's terminal declaration for a destructive stub (e.g. `_delete_entity`). */
export function terminalOperation(tool) {
  return {
    tool,
    operations: ["delete"],
    note: "Scaffold default: treat delete as irreversible until the platform's restore behaviour is checked.",
  };
}

export const KEY_PATTERN = /^[a-z][a-z0-9_]{1,39}$/;

const EXCEPTION_REASON = "Not generated by the scaffold; add the tool or keep this reason";

/** `foo_bar` → `{ key: "foo_bar", package: "foo-bar-mcp", Pascal: "FooBar", ENV: "FOO_BAR" }`. */
export function names(key) {
  if (!KEY_PATTERN.test(key)) {
    throw new Error(`platform key "${key}" must match ${KEY_PATTERN} (lower snake case)`);
  }
  return {
    key,
    package: `${key.replaceAll("_", "-")}-mcp`,
    Pascal: key
      .split("_")
      .map((w) => w[0].toUpperCase() + w.slice(1))
      .join(""),
    ENV: key.toUpperCase(),
  };
}

/** One past the highest port in the registry. */
export function nextFreePort(registry) {
  return Math.max(...registry.servers.map((s) => s.port)) + 1;
}

/** A complete registry entry for a scaffolded server shipping `tools`. */
export function buildRegistryEntry(opts, registry, tools) {
  const n = names(opts.key);
  const tier = SERVER_TYPES[opts.type];
  if (!tier)
    throw new Error(`server type "${opts.type}" is not one of ${Object.keys(SERVER_TYPES)}`);
  const partial = { tool_prefix: n.key, tools };
  const exceptions = tier.should
    .filter((req) => !meets(partial, req))
    .map((requirement) => ({ requirement, reason: EXCEPTION_REASON }));

  return {
    package: n.package,
    port: opts.port ?? nextFreePort(registry),
    tool_prefix: n.key,
    platform_key: n.key,
    type: opts.type,
    // New servers start experimental: built and tested, never published or
    // deployed until `pnpm promote:server` (scripts/lib/server-status.mjs).
    status: "experimental",
    ...(exceptions.length ? { contract: { exceptions } } : {}),
    // Ungoverned means no write tools (scripts/lib/governed-packages.mjs).
    governed: Boolean(opts.writes),
    title: `${opts.displayName} MCP Server`,
    description: `${opts.displayName} ${templateType(opts.type).description} (scaffolded; experimental)`,
    runtime_description: `${opts.displayName} API: ${templateType(opts.type).runtime}.`,
    platform: opts.displayName,
    platform_display_name: opts.displayName,
    documentation_url: opts.docsUrl,
    tools,
    // What the template registers (check:registry-runtime compares them live).
    resources: [`tool-examples://${n.package}/all`, `server-capabilities://${n.package}/overview`],
    prompts: ["cross_platform_performance_comparison", "cross_platform_campaign_setup"],
    auth: { modes: [`${n.key}-bearer`, "jwt", "none"] },
    tags: ["advertising", n.key, "campaign-management"],
    untrustedContent: { pathReporting: "per-response" },
    operational: {
      terminalOperations: opts.writes
        ? templateType(opts.type).terminalTools.map((t) => terminalOperation(`${n.key}_${t}`))
        : [],
    },
  };
}

function addDays(isoDate, days) {
  const d = new Date(`${isoDate}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

/**
 * The two facts every scaffolded server relies on: its API base and its
 * default rate limit. `configLines` are the 1-based lines of those values in
 * the template's `src/config/index.ts` (Task 3's CONFIG_LINES).
 */
export function buildPlatformFacts(opts, today, configLines) {
  const n = names(opts.key);
  const configRef = (line) => [`packages/${n.package}/src/config/index.ts:${line}`];
  const host = new URL(opts.baseUrl).host;
  const fact = (cls, fields) => ({
    id: fields.id,
    package: n.package,
    class: cls,
    claim: fields.claim,
    value: fields.value,
    sourceUrl: opts.docsUrl,
    status: "unverified",
    verifiedAt: null,
    verifyBy: addDays(today, REFRESH_DAYS[cls]),
    refreshDue: null,
    loadBearing: fields.loadBearing,
    codeRefs: fields.codeRefs,
  });
  return [
    fact("unversioned-base-url", {
      id: `${n.key}.api_base`,
      claim: `${host} is the current API base for ${opts.displayName} (recorded by the scaffold; verify against the vendor docs)`,
      value: opts.baseUrl,
      loadBearing: false,
      codeRefs: configRef(configLines.baseUrl),
    }),
    fact("behavioral-constraint", {
      id: `${n.key}.rate_limit_default`,
      claim: `The per-process default of ${opts.rateLimitPerMinute} requests/min stays within ${opts.displayName}'s API quota across the fleet's assumed 10 instances (scaffold default; verify the vendor's quota before relying on it)`,
      value: `default(${opts.rateLimitPerMinute})`,
      loadBearing: true,
      codeRefs: configRef(configLines.rateLimit),
    }),
  ];
}
